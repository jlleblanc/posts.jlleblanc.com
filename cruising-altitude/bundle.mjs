// Dev-only bundler: concatenates js/ modules into bundle.js (classic script)
// so the game runs from file:// where ES modules are blocked by CORS.
// Usage: node bundle.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const order = ['data.js', 'seed.js', 'time.js', 'schedule.js', 'people.js', 'encounters.js', 'loyalty.js', 'app.js'];

let out = '// Cruising Altitude bundle — generated by node bundle.mjs. Do not edit by hand.\n';
out += `'use strict';\n`;

for (const file of order) {
  let src = readFileSync(join(root, 'js', file), 'utf8');
  // Strip import blocks (single- and multi-line).
  src = src.replace(/import\s*{[^}]*}\s*from\s*['"][^'"]+['"];?/gs, '');
  // Strip `export ` prefix on declarations.
  src = src.replace(/^export\s+(const|let|function|class)\s+/gm, '$1 ');
  // Fail loudly on anything we don't know how to strip.
  if (/^\s*(import|export)\s/m.test(src)) {
    console.error(`UNHANDLED import/export in ${file}`);
    process.exit(1);
  }
  out += `\n/* ---- ${file} ---- */\n${src.trim()}\n`;
}

writeFileSync(join(root, 'bundle.js'), out);
console.log(`bundle.js written (${out.length} bytes)`);
